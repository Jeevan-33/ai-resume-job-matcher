def build_description(intro: str, responsibilities: list[str], requirements: list[str], nice_to_have: list[str] | None = None) -> str:
    parts = [intro, "", "What you'll do:"]
    parts += [f"- {r}" for r in responsibilities]
    parts += ["", "What we're looking for:"]
    parts += [f"- {r}" for r in requirements]
    if nice_to_have:
        parts += ["", "Nice to have:"]
        parts += [f"- {r}" for r in nice_to_have]
    return "\n".join(parts)



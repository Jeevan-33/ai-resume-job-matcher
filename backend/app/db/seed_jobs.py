def seed(reset: bool = True):
    db = SessionLocal()
    try:
        if reset:
            db.query(Job).delete()
            db.commit()

        for job_data in JOBS:
            category = classify_category(job_data["title"], job_data.get("skills"))
            db.add(Job(source="Internal", category=category, **job_data))

        db.commit()
        print(f"Seeded {len(JOBS)} jobs.")
    finally:
        db.close()


